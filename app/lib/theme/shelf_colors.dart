import 'package:material_ui/material_ui.dart';

/// The themes' families, in the order the theme sheet shows them.
enum ThemeFamily {
  woodgrain('Woodgrain'),
  finishes('Finishes'),
  classic('Classic');

  const ThemeFamily(this.label);

  final String label;
}

/// The themes to choose from; tobacco is the default. Woodgrain: warm
/// browns without light windows; Finishes: colours after guitar finishes and
/// retro gear (docs/design/visual/variations/themes-*.html); Classic: the
/// original amber themes with light windows.
enum AppTheme {
  tobacco('Tobacco & copper', ThemeFamily.woodgrain, ShelfColors.tobacco),
  ember('Ember', ThemeFamily.woodgrain, ShelfColors.ember),
  cognac('Cognac & cream', ThemeFamily.woodgrain, ShelfColors.cognac),
  spaceAge('Space age', ThemeFamily.woodgrain, ShelfColors.spaceAge),
  tubeAmp('Tube amp', ThemeFamily.woodgrain, ShelfColors.tubeAmp),
  cassette('Cassette chrome', ThemeFamily.woodgrain, ShelfColors.cassette),
  atomicCream('Atomic cream', ThemeFamily.woodgrain, ShelfColors.atomicCream),
  sunburst('Sunburst', ThemeFamily.finishes, ShelfColors.sunburst),
  sonicBlue('Sonic blue', ThemeFamily.finishes, ShelfColors.sonicBlue),
  surfGreen('Surf green', ThemeFamily.finishes, ShelfColors.surfGreen),
  candyRed('Candy red', ThemeFamily.finishes, ShelfColors.candyRed),
  shellPink('Shell pink', ThemeFamily.finishes, ShelfColors.shellPink),
  tangerineNight(
    'Tangerine night',
    ThemeFamily.finishes,
    ShelfColors.tangerineNight,
  ),
  studioOrange('Studio orange', ThemeFamily.finishes, ShelfColors.studioOrange),
  tealMustard('Teal & mustard', ThemeFamily.finishes, ShelfColors.tealMustard),
  evening('Evening', ThemeFamily.classic, ShelfColors.evening),
  daylight('Daylight', ThemeFamily.classic, ShelfColors.daylight);

  const AppTheme(this.label, this.family, this.colors);

  final String label;
  final ThemeFamily family;
  final ShelfColors colors;
}

